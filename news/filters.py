def order_reject_reason(title, desc):
    """Почему заказ не подошёл. None — подходит.

    Заказ проходит, если он про ИИ ИЛИ про сайты (сайты — без требования ИИ).
    """
    text = (title + " " + desc).lower()
    if any(w in text for w in ORDER_AD_MARKERS):
        return "реклама или SEO, а не разработка"
    if any(w in text for w in ORDER_ARTICLE_MARKERS):
        return "это статья, а не заказ"
    if any(w in text for w in SITE_MARKERS):
        return None
    if has_ai_signal(text):
        return None
    if any(w in text for w in ORDER_AUTOMATION_MARKERS):
        return None
    return "нет признака ИИ или сайта"


def is_ai_order(title, desc):
    """Заказ проходит, если он про ИИ ИЛИ про сайты (сайты — без требования ИИ)."""
    return order_reject_reason(title, desc) is None


