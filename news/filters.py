def job_reject_reason(title, desc, remote_confirmed=False):
    """Почему вакансия не подошла. None — подходит.

    Правило заказчика: только удалённая работа и только по-русски. «Заумные»
    англоязычные вакансии и работа у работодателя в офисе не нужны.

    remote_confirmed=True значит, что источник уже отфильтровал вакансии по
    формату работы — так делают hh.ru (лента с schedule=remote) и «Работа
    России» (поле employment). В этом случае проверять формат по тексту
    нельзя: hh.ru в RSS его не пишет вовсе (см. REMOTE_MARKERS).
    """
    text = (title + " " + desc).lower()

    # 1. Язык. Кириллицы нет вовсе — вакансия англоязычная, не берём.
    if detect_lang(title + " " + desc) == "en":
        return "вакансия на английском"

    # 2. Формат работы. Если источник сам не отфильтровал — требуем, чтобы
    #    удалёнка была названа в тексте.
    if not remote_confirmed and not any(w in text for w in REMOTE_MARKERS):
        return "не сказано про удалёнку"

    # 3. Профессия в заголовке — самый сильный признак «не наша вакансия»:
    #    «Продавец-консультант», «Курьер», «Менеджер по продажам».
    if any(w in title.lower() for w in JOB_BLOCK_PROFESSIONS):
        return "не ИИ-профессия"

    # 4. Вакансия должна быть про ИИ или ML. Одного технического слова мало:
    #    поиск hh.ru нечёткий и подсовывает посторонние профессии.
    if not is_ai_job_theme(text):
        return "нет признака ИИ или ML"

    # 5. То же блок-слово, но в описании — по узкому списку. Причина названа
    #    отдельно, и это не придирка к формулировке: по такой пометке видно,
    #    какие правила стоит пересмотреть. Так нашлись «Аналитик-инженер
    #    по машинному обучению» (слово «водитель») и «AI-тренер для обучения
    #    нейросетей» (слово «контент»).
    if any(w in text for w in JOB_BLOCK_IN_DESC):
        return "не ИИ-профессия (слово в описании)"

    # 6. Курсы, обучения и стажировки
    if any(w in text for w in JOB_EDU_MARKERS):
        return "курсы или обучение, а не вакансия"
    return None


def is_real_ai_job(title, desc, remote_confirmed=False):
    """Проверяет, что это релевантная онлайн/удалённая AI-вакансия."""
    return job_reject_reason(title, desc, remote_confirmed) is None


